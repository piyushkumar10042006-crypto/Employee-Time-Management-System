package com.timemanagement;

import com.timemanagement.db.DBConnection;
import com.timemanagement.db.DBInitializer;
import com.timemanagement.exception.AttendanceException;
import com.timemanagement.exception.AuthenticationException;
import com.timemanagement.model.AttendanceRecord;
import com.timemanagement.model.Employee;
import com.timemanagement.model.LeaveRequest;
import com.timemanagement.model.Manager;
import com.timemanagement.model.User;
import com.timemanagement.model.enums.LeaveStatus;
import com.timemanagement.model.enums.LeaveType;
import com.timemanagement.service.AttendanceService;
import com.timemanagement.service.AuthService;
import com.timemanagement.service.LeaveService;
import com.timemanagement.service.ReportService;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.File;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

/**
 * End-to-end Integration Test (JUnit 5) verifying Live Database Operations,
 * Authentication, Punch In/Out, Leave Workflow, and Report Export.
 *
 * SAFETY INVARIANTS:
 * 1. Strictly targets 'employee_time_test_db'. Never touches 'employee_time_db'.
 * 2. Does not delete pre-existing records; tracks and cleans up only rows created
 *    by the current test execution using exact generated IDs.
 * 3. Leases isolated pooled connections through try-with-resources.
 * 4. Ensures temporary exported files are cleaned up in finally blocks.
 */
public class LiveDatabaseIntegrationTest {

    private static final String TEST_DB_URL = "jdbc:mysql://localhost:3306/employee_time_test_db?useSSL=false&allowPublicKeyRetrieval=true&serverTimezone=UTC&createDatabaseIfNotExist=true";

    @BeforeAll
    static void setUpAll() throws Exception {
        DBConnection.reinitializeForDatabase(TEST_DB_URL);
        DBInitializer.initializeDatabase();
    }

    // 1. Database Connection & Schema Initialization
    @Test
    @DisplayName("1. Database Connection & Schema Initialization")
    void testDatabaseInit() {
        assertDoesNotThrow(() -> DBInitializer.initializeDatabase(), "Schema initialization must be idempotent and succeed");
        try (Connection conn = DBConnection.getInstance().getConnection()) {
            assertNotNull(conn, "Active MySQL Connection leased from pool must not be null");
            assertFalse(conn.isClosed(), "Active MySQL Connection leased from pool must be open");
        } catch (Exception e) {
            fail("Failed to verify active database connection: " + e.getMessage());
        }
    }

    // 2. Employee Authentication (Valid & Invalid)
    @Test
    @DisplayName("2. Employee Authentication (Valid & Invalid)")
    void testEmployeeAuth() throws Exception {
        AuthService auth = new AuthService();
        User emp = auth.login("employee@company.com", "employee123");
        assertNotNull(emp, "Authenticated employee must not be null");
        assertTrue(emp instanceof Employee, "Authenticated user must be an Employee");
        assertFalse(emp.canApproveLeaves(), "Standard employee cannot approve leaves");

        // Verify invalid credentials throw AuthenticationException
        assertThrows(AuthenticationException.class, () -> {
            auth.login("employee@company.com", "wrongpassword");
        }, "Invalid credentials must throw AuthenticationException");
    }

    // 3. Manager Authentication & Permissions
    @Test
    @DisplayName("3. Manager Authentication & Permissions")
    void testManagerAuth() throws Exception {
        AuthService auth = new AuthService();
        User mgr = auth.login("manager@company.com", "manager123");
        assertNotNull(mgr, "Authenticated manager must not be null");
        assertTrue(mgr instanceof Manager, "Authenticated user must be a Manager");
        assertTrue(mgr.canApproveLeaves(), "Manager must have leave approval permissions");
    }

    // 4. Attendance Punch-In, Punch-Out & Validation
    @Test
    @DisplayName("4. Attendance Punch-In, Punch-Out & Validation")
    void testAttendanceWorkflow() throws Exception {
        AuthService auth = new AuthService();
        User emp = auth.login("david@company.com", "david123");
        AttendanceService att = new AttendanceService();

        int createdRecordId = 0;
        try {
            // 1. Clock In
            AttendanceRecord record = att.clockIn(emp, "Testing live check-in");
            assertNotNull(record, "Clock in record must exist");
            assertNotNull(record.getClockIn(), "Clock in time must be stored");
            createdRecordId = record.getRecordId();
            assertTrue(createdRecordId > 0, "Record ID must be generated by DB");

            // 2. Prevent duplicate clock-in
            assertThrows(AttendanceException.class, () -> {
                att.clockIn(emp, "Duplicate check-in attempt");
            }, "Duplicate clock-in attempt must throw AttendanceException");

            // 3. Clock Out
            boolean clockedOut = att.clockOut(emp);
            assertTrue(clockedOut, "Clock out must return true");

            // 4. Verify in DB
            Optional<AttendanceRecord> todayOpt = att.getTodayRecord(emp.getUserId());
            assertTrue(todayOpt.isPresent(), "Today's record must be present");
            assertNotNull(todayOpt.get().getClockOut(), "Clock out time must be stored");
            assertEquals(createdRecordId, todayOpt.get().getRecordId(), "Record ID must match created shift");
        } finally {
            // Track and clean up ONLY the record created by this test execution using its exact ID
            if (createdRecordId > 0) {
                try (Connection conn = DBConnection.getInstance().getConnection();
                     PreparedStatement stmt = conn.prepareStatement("DELETE FROM attendance WHERE record_id = ?")) {
                    stmt.setInt(1, createdRecordId);
                    stmt.executeUpdate();
                } catch (Exception ex) {
                    System.err.println("Warning: Failed to clean up test attendance record " + createdRecordId + ": " + ex.getMessage());
                }
            }
        }
    }

    // 5. Leave Request Submission & Manager Approval
    @Test
    @DisplayName("5. Leave Request Submission & Manager Approval")
    void testLeaveWorkflow() throws Exception {
        AuthService auth = new AuthService();
        User emp = auth.login("emily@company.com", "emily123");
        User mgr = auth.login("manager@company.com", "manager123");
        LeaveService leaveService = new LeaveService();

        LocalDate start = LocalDate.now().plusDays(20);
        LocalDate end = LocalDate.now().plusDays(21); // 2 days

        int createdLeaveId = 0;
        try {
            // 1. Employee applies for leave
            LeaveRequest req = leaveService.applyLeave(emp, LeaveType.VACATION, start, end, "E2E Integration Test");
            assertNotNull(req, "Leave request must not be null");
            createdLeaveId = req.getLeaveId();
            assertTrue(createdLeaveId > 0, "Leave ID must be generated by DB");
            assertEquals(LeaveStatus.PENDING, req.getStatus(), "Initial leave status must be PENDING");

            // 2. Manager reviews and approves
            boolean approved = leaveService.reviewLeave(req.getLeaveId(), LeaveStatus.APPROVED, mgr);
            assertTrue(approved, "Leave review approval must succeed");

            // 3. Verify status in DB
            List<LeaveRequest> userLeaves = leaveService.getUserLeaves(emp.getUserId());
            final int leaveIdToCheck = createdLeaveId;
            boolean foundApproved = userLeaves.stream()
                    .anyMatch(l -> l.getLeaveId() == leaveIdToCheck && l.getStatus() == LeaveStatus.APPROVED);
            assertTrue(foundApproved, "Leave record must be marked APPROVED in DB");
        } finally {
            // Track and clean up ONLY the record created by this test execution using its exact ID
            if (createdLeaveId > 0) {
                try (Connection conn = DBConnection.getInstance().getConnection();
                     PreparedStatement stmt = conn.prepareStatement("DELETE FROM leave_requests WHERE leave_id = ?")) {
                    stmt.setInt(1, createdLeaveId);
                    stmt.executeUpdate();
                } catch (Exception ex) {
                    System.err.println("Warning: Failed to clean up test leave record " + createdLeaveId + ": " + ex.getMessage());
                }
            }
        }
    }

    // 6. Reports Calculation & TXT File Export
    @Test
    @DisplayName("6. Reports Calculation & TXT File Export")
    void testReportAndExport() throws Exception {
        AuthService auth = new AuthService();
        User emp = auth.login("employee@company.com", "employee123");
        ReportService rpt = new ReportService();

        String reportText = rpt.generateUserMonthlyReport(emp.getUserId(), emp.getName());
        assertNotNull(reportText, "Report text must not be null");
        assertTrue(reportText.contains("EMPLOYEE TIME & ATTENDANCE SUMMARY REPORT"),
                "Report text must contain header");

        File tempExport = new File("target/test_export.txt");
        try {
            tempExport.getParentFile().mkdirs();
            try (PrintWriter out = new PrintWriter(tempExport)) {
                out.print(reportText);
            }

            assertTrue(tempExport.exists() && tempExport.length() > 0, "Exported file must exist and not be empty");
            String readBack = Files.readString(tempExport.toPath());
            assertTrue(readBack.contains(emp.getName()), "Exported content must match generated report");
        } finally {
            // Temporary file cleaned up even when tests fail
            if (tempExport.exists()) {
                tempExport.delete();
            }
        }
    }
}
